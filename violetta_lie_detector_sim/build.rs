//! Embeds the sprite artwork, its animation frames and its pivots.
//!
//! Every PNG in `Resources/` — and the one JPEG — is baked into the binary, so
//! there is nothing to fetch at run time and no asset path to get wrong. What sits
//! in a subdirectory is a *language*: `Resources/kr/` holds the artwork that
//! replaces the base sprite of the same name while Korean is being shown, so a
//! language only has to carry what it translates, and one that is missing a sprite
//! falls back to the base artwork. Three tables are generated:
//!
//! * [`SPRITES`] – sprite name to file contents and pivot.
//! * [`FRAME_GROUPS`] – animation group to its frames, in index order.
//! * [`LANGUAGE_SPRITES`] – language to the sprites it replaces.
//!
//! ### Pivots
//!
//! Each frame of an animation is trimmed to its own drawing, so the images differ
//! in size and in where the drawing sits inside them. The game records a pivot
//! for every image, and a frame drawn with its pivot on a fixed point is what
//! stops an animation from shaking. Those pivots are kept in
//! `Resources/sprite-pivots.txt`, alongside the artwork they describe; a sprite
//! missing from it falls back to the corner of its image and will jitter.
//!
//! The tables are regenerated whenever `Resources/` changes, so adding artwork
//! needs no code change at all.

use std::{
    collections::{BTreeMap, BTreeSet},
    env, fs,
    path::Path,
};

/// Recorded pivot of every sprite, keyed by file name without the extension.
const PIVOT_FILE: &str = "sprite-pivots.txt";

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo");
    let resources = Path::new(&manifest_dir).join("..").join("Resources");
    println!("cargo:rerun-if-changed={}", resources.display());

    let mut paths: Vec<_> = fs::read_dir(&resources)
        .unwrap_or_else(|err| panic!("cannot read {}: {err}", resources.display()))
        .map(|entry| entry.expect("readable directory entry").path())
        .collect();
    paths.sort();

    let mut sprites: Vec<(String, String)> = Vec::new();
    let mut groups: BTreeMap<String, Vec<(u32, String)>> = BTreeMap::new();
    let mut languages: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new();

    for path in paths {
        if path.is_dir() {
            let language = path
                .file_name()
                .and_then(|name| name.to_str())
                .expect("language directory names are UTF-8")
                .to_owned();
            println!("cargo:rerun-if-changed={}", path.display());

            let mut translated: Vec<(String, String)> = fs::read_dir(&path)
                .unwrap_or_else(|err| panic!("cannot read {}: {err}", path.display()))
                .map(|entry| entry.expect("readable directory entry").path())
                .filter(|path| is_artwork(path))
                .map(|path| (sprite_name(&path), file_path(&path)))
                .collect();
            translated.sort();
            if !translated.is_empty() {
                languages.insert(language, translated);
            }
            continue;
        }

        if !is_artwork(&path) {
            continue;
        }
        let name = sprite_name(&path);
        let file = file_path(&path);

        // `lieDetector.npc.stand.3` is frame 3 of the `lieDetector.npc.stand` group.
        if let Some((group, frame)) = name.rsplit_once('.')
            && let Ok(frame) = frame.parse::<u32>()
        {
            groups
                .entry(group.to_owned())
                .or_default()
                .push((frame, name.clone()));
        }

        sprites.push((name, file));
    }

    // Pivots live next to the artwork, so the build needs no reference material.
    let pivot_file = resources.join(PIVOT_FILE);
    println!("cargo:rerun-if-changed={}", pivot_file.display());
    let pivots = read_pivots(&pivot_file);

    sprites.sort_by(|a, b| a.0.cmp(&b.0));
    for pair in sprites.windows(2) {
        assert_ne!(
            pair[0].0, pair[1].0,
            "duplicate sprite name `{}`",
            pair[0].0
        );
    }

    let names: BTreeSet<&str> = sprites.iter().map(|(name, _)| name.as_str()).collect();
    for unknown in pivots.keys().filter(|name| !names.contains(name.as_str())) {
        println!(
            "cargo:warning={PIVOT_FILE} has an entry for `{unknown}`, which is not a sprite in \
             Resources/"
        );
    }

    let mut code = String::from("// @generated by build.rs - do not edit.\n\n");
    code.push_str("/// Every sprite in `Resources/`, keyed by file name without the extension,\n");
    code.push_str("/// with the pivot its drawing sits at, in image pixels.\n");
    code.push_str("pub static SPRITES: &[(&str, &[u8], (i32, i32))] = &[\n");
    for (name, file) in &sprites {
        let (pivot_x, pivot_y) = pivots.get(name).copied().unwrap_or((0, 0));
        code.push_str(&format!(
            "    ({name:?}, include_bytes!({file:?}), ({pivot_x}, {pivot_y})),\n"
        ));
    }
    code.push_str("];\n\n");
    code.push_str(
        "/// Animation frames in `Resources/`, keyed by the sprite name without its `.N` suffix.\n",
    );
    code.push_str("pub static FRAME_GROUPS: &[(&str, &[&str])] = &[\n");
    for (group, mut frames) in groups {
        frames.sort_by_key(|(frame, _)| *frame);
        code.push_str(&format!("    ({group:?}, &["));
        for (_, name) in &frames {
            code.push_str(&format!("{name:?}, "));
        }
        code.push_str("]),\n");
    }
    code.push_str("];\n\n");

    code.push_str("/// The artwork each language replaces, keyed by language and then by the\n");
    code.push_str(
        "/// sprite name it stands in for. A language carries only what it translates:\n",
    );
    code.push_str(
        "/// a sprite it does not have is drawn from the base artwork of the same name,\n",
    );
    code.push_str("/// pivot included, since a translation is drawn where the original was.\n");
    code.push_str("pub static LANGUAGE_SPRITES: &[(&str, LanguageSprites)] = &[\n");
    for (language, translated) in &languages {
        code.push_str(&format!("    ({language:?}, &[\n"));
        for (name, file) in translated {
            let (pivot_x, pivot_y) = pivots.get(name).copied().unwrap_or((0, 0));
            code.push_str(&format!(
                "        ({name:?}, include_bytes!({file:?}), ({pivot_x}, {pivot_y})),\n"
            ));
        }
        code.push_str("    ]),\n");
    }
    code.push_str("];\n");

    let out = Path::new(&env::var("OUT_DIR").expect("OUT_DIR is set by cargo")).join("sprites.rs");
    fs::write(&out, code).expect("writable build output directory");
}

/// Whether `path` is artwork the build embeds: a PNG, or the JPEG the title screen
/// uses as its background.
fn is_artwork(path: &Path) -> bool {
    matches!(
        path.extension().and_then(|ext| ext.to_str()),
        Some("png" | "jpg" | "jpeg")
    )
}

/// The name `path` is indexed under: its file name without the extension.
///
/// `lieDetector.gameEffect.emphasis .0.png` has a stray space in the name; folding
/// it away gives every sprite a tidy, uniform key.
fn sprite_name(path: &Path) -> String {
    path.file_stem()
        .and_then(|stem| stem.to_str())
        .expect("sprite file names are UTF-8")
        .replace(" .", ".")
}

/// `path` as `include_bytes!` wants it.
fn file_path(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

/// Reads every sprite pivot out of `Resources/sprite-pivots.txt`.
///
/// The file holds one `<sprite name> <x> <y>` per line, where the X and Y are in
/// image pixels; blank lines and `#` comments are ignored.
fn read_pivots(path: &Path) -> BTreeMap<String, (i32, i32)> {
    let mut pivots = BTreeMap::new();
    let Ok(text) = fs::read_to_string(path) else {
        println!(
            "cargo:warning={} is missing, so every sprite pivot defaults to the corner of its \
             image and animated sprites will shake",
            path.display()
        );
        return pivots;
    };

    for (index, raw) in text.lines().enumerate() {
        let line_number = index + 1;
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let mut fields = line.split_whitespace();
        let (Some(name), Some(x), Some(y), None) =
            (fields.next(), fields.next(), fields.next(), fields.next())
        else {
            malformed(path, line_number, line);
        };
        let (Ok(x), Ok(y)) = (x.parse(), y.parse()) else {
            malformed(path, line_number, line);
        };

        let replaced = pivots.insert(name.to_owned(), (x, y));
        assert!(
            replaced.is_none(),
            "{} line {line_number}: a second entry for sprite `{name}`",
            path.display()
        );
    }

    pivots
}

/// Reports a line that is not `<sprite name> <x> <y>`.
fn malformed(path: &Path, line_number: usize, line: &str) -> ! {
    panic!(
        "{} line {line_number}: expected `<sprite name> <x> <y>`, got `{line}`",
        path.display()
    )
}
